// Renders the project grid shared by the profile READMEs from assets/brand/brand.toml, so the
// cards, icons and one-line purposes stay identical to the brand source.
// Usage: bun docs/profile/projects.ts  (rewrites the <!-- projects --> blocks in place)
import { join } from "node:path";

const ROOT = join(import.meta.dir, "..", "..");
const CDN = "https://cdn.aphrody.com/brand/v1";
const REPO = "https://github.com/aphrody-labs/src/tree/main";
type P = { id: string; name: string; tagline: string; path: string };
const brand = Bun.TOML.parse(
  await Bun.file(join(ROOT, "assets/brand/brand.toml")).text(),
) as { product: P[] };

// Public link targets only: apps whose source lives in a public repository.
const external: Record<string, string> = {
  shenron: "https://github.com/aphrody-labs/shenron",
  rosegriffon: "https://github.com/aphrody-labs/rosegriffon",
};
const cell = (p: P) => {
  const href = external[p.id] ?? `${REPO}/${p.path}`;
  return `<td width="33%" valign="top"><a href="${href}"><img src="${CDN}/icons/${p.id}/icon.svg" width="40" height="40" alt=""></a><br><b><a href="${href}">${p.name}</a></b><br><sub>${p.tagline}</sub></td>`;
};
const rows: string[] = [];
for (let i = 0; i < brand.product.length; i += 3)
  rows.push(
    `<tr>\n${brand.product
      .slice(i, i + 3)
      .map(cell)
      .join("\n")}\n</tr>`,
  );
const grid = `<!-- projects:start (generated by docs/profile/projects.ts) -->\n<table>\n${rows.join("\n")}\n</table>\n<!-- projects:end -->`;

for (const f of [
  "github/aphrody-labs/.github/profile/README.md",
  "github/aphrody-dev/README.md",
]) {
  const path = join(import.meta.dir, f);
  const text = await Bun.file(path).text();
  const out = text.replace(
    /<!-- projects:start[\s\S]*?<!-- projects:end -->/,
    grid,
  );
  await Bun.write(path, out);
  console.log(f);
}
