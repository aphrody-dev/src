// One recipe (infra/pkg/recipes/<name>.toml) -> PKGBUILD, debian/, APKBUILD, ebuild, Android.bp,
// a Nix derivation and an OCI layer image. Each generator also writes build.sh, the script that builds
// and install-tests the package inside the distro container of infra/pkg/distros.toml (mounted at /w).

import { readFileSync, readdirSync, existsSync } from "node:fs";
import { basename, join, posix } from "node:path";

export type FileSpec = { src: string; dest: string; mode?: string };

export type Recipe = {
  name: string;
  version: string;
  release: number;
  date: string;
  summary: string;
  description: string;
  license: string;
  homepage: string;
  maintainer: string;
  arch: "all";
  portage_category?: string;
  targets: string[];
  files: FileSpec[];
  depends?: Record<string, string[]>;
};

export type Distro = {
  name: string;
  format: Format;
  image?: string;
  nixpkgs?: string;
  ci: boolean;
};

export const FORMATS = ["arch", "debian", "alpine", "portage", "soong", "nix", "docker"] as const;
export type Format = (typeof FORMATS)[number];
/** Target names of a recipe (`targets`) per format. */
export const TARGET_OF: Record<Format, string> = {
  arch: "arch",
  debian: "debian",
  alpine: "alpine",
  portage: "portage",
  soong: "android",
  nix: "nix",
  docker: "docker",
};

export type Output = { files: Record<string, string | Uint8Array>; modes: Record<string, number> };

const RECIPES = join("infra", "pkg", "recipes");

export function loadRecipes(root: string): Recipe[] {
  const dir = join(root, RECIPES);
  return readdirSync(dir)
    .filter((f) => f.endsWith(".toml"))
    .sort()
    .map((f) => validate(Bun.TOML.parse(readFileSync(join(dir, f), "utf8")) as Recipe, f));
}

export function loadDistros(root: string): Distro[] {
  const doc = Bun.TOML.parse(readFileSync(join(root, "infra", "pkg", "distros.toml"), "utf8")) as {
    distro: Record<string, Omit<Distro, "name">>;
  };
  return Object.entries(doc.distro).map(([name, d]) => ({ name, ...d }));
}

function validate(r: Recipe, file: string): Recipe {
  for (const k of ["name", "version", "summary", "description", "license", "homepage", "maintainer", "date"] as const)
    if (!r[k]) throw new Error(`${file}: champ ${k} manquant`);
  if (`${r.name}.toml` !== file) throw new Error(`${file}: name = "${r.name}" ne correspond pas au fichier`);
  if (!/^[a-z0-9][a-z0-9+.-]*$/.test(r.name)) throw new Error(`${file}: nom de paquet invalide`);
  if (r.arch !== "all") throw new Error(`${file}: seul arch = "all" est pris en charge`);
  if (!r.files?.length) throw new Error(`${file}: aucun [[files]]`);
  for (const f of r.files) if (!f.dest.startsWith("/")) throw new Error(`${file}: dest ${f.dest} non absolu`);
  const names = r.files.map((f) => basename(f.src));
  if (new Set(names).size !== names.length) throw new Error(`${file}: deux fichiers de même nom`);
  r.release ??= 1;
  return r;
}

const mode = (f: FileSpec) => f.mode ?? "644";
const sha = (algo: "sha256" | "sha512", b: Uint8Array) => new Bun.CryptoHasher(algo).update(b).digest("hex");
const header = (r: Recipe, c = "#") => `${c} Generated by \`ay pkg gen\` from infra/pkg/recipes/${r.name}.toml. Do not edit.\n`;
const q = (s: string) => s.replace(/(["\\$`])/g, "\\$1");

function sources(root: string, r: Recipe): Map<string, Uint8Array> {
  const m = new Map<string, Uint8Array>();
  for (const f of r.files) {
    const p = join(root, f.src);
    if (!existsSync(p)) throw new Error(`${r.name}: ${f.src} introuvable`);
    m.set(basename(f.src), new Uint8Array(readFileSync(p)));
  }
  return m;
}

/** SPDX expression -> Gentoo LICENSE ("MIT OR Apache-2.0" -> "|| ( MIT Apache-2.0 )"). */
export function gentooLicense(spdx: string): string {
  const alts = spdx.split(/\s+OR\s+/);
  return alts.length > 1 ? `|| ( ${alts.join(" ")} )` : spdx;
}

/** SPDX expression -> nixpkgs lib.licenses attributes. */
export function nixLicenses(spdx: string): string {
  const map: Record<string, string> = {
    MIT: "mit",
    "Apache-2.0": "asl20",
    "GPL-2.0-only": "gpl2Only",
    "GPL-3.0-only": "gpl3Only",
    "BSD-3-Clause": "bsd3",
  };
  return spdx
    .split(/\s+(?:OR|AND)\s+/)
    .map((l) => map[l] ?? `{ spdxId = "${l}"; }`)
    .join(" ");
}

function rfc2822(date: string): string {
  return new Date(`${date}T00:00:00Z`).toUTCString().replace("GMT", "+0000");
}

export function generate(root: string, r: Recipe, format: Format, distro?: Distro): Output {
  if (!r.targets.includes(TARGET_OF[format]))
    throw new Error(`${r.name}: cible ${TARGET_OF[format]} absente de targets`);
  const src = sources(root, r);
  const out: Output = { files: {}, modes: {} };
  const put = (p: string, c: string | Uint8Array, m?: number) => {
    out.files[p] = c;
    if (m) out.modes[p] = m;
  };
  const deps = r.depends?.[TARGET_OF[format]] ?? [];
  switch (format) {
    case "arch": {
      const names = [...src.keys()];
      put(
        "PKGBUILD",
        header(r) +
          `# Maintainer: ${r.maintainer}\n` +
          `pkgname=${r.name}\npkgver=${r.version}\npkgrel=${r.release}\n` +
          `pkgdesc="${q(r.summary)}"\narch=('any')\nurl="${r.homepage}"\nlicense=('${r.license}')\n` +
          `depends=(${deps.map((d) => `'${d}'`).join(" ")})\n` +
          `source=(${names.map((n) => `'${n}'`).join(" ")})\n` +
          `sha256sums=(${names.map((n) => `'${sha("sha256", src.get(n)!)}'`).join(" ")})\n\n` +
          `package() {\n` +
          r.files.map((f) => `  install -Dm${mode(f)} "$srcdir/${basename(f.src)}" "$pkgdir${f.dest}"\n`).join("") +
          `}\n`,
      );
      for (const [n, b] of src) put(n, b);
      put(
        "build.sh",
        `#!/bin/sh\n${header(r)}set -eu\n` +
          `pacman -Syu --noconfirm --needed base-devel\n` +
          `id build >/dev/null 2>&1 || useradd -m build\nchown -R build /w\n` +
          `su build -c 'cd /w && makepkg -fd --noconfirm'\n` +
          `pacman -U --noconfirm /w/${r.name}-${r.version}-${r.release}-any.pkg.tar.zst\n` +
          r.files.map((f) => `test -f ${f.dest}\n`).join("") +
          `pacman -Qi ${r.name} | head -3\n`,
        0o755,
      );
      break;
    }
    case "debian": {
      const d = `${r.name}-${r.version}`;
      const pkgDeps = ["${misc:Depends}", ...deps].join(", ");
      put(
        `${d}/debian/control`,
        `Source: ${r.name}\nSection: admin\nPriority: optional\nMaintainer: ${r.maintainer}\n` +
          `Build-Depends: debhelper-compat (= 13)\nStandards-Version: 4.7.4\nHomepage: ${r.homepage}\n` +
          `Rules-Requires-Root: no\n\nPackage: ${r.name}\nArchitecture: all\nDepends: ${pkgDeps}\n` +
          `Description: ${r.summary}\n ${r.description}\n`,
      );
      put(
        `${d}/debian/changelog`,
        `${r.name} (${r.version}-${r.release}) unstable; urgency=medium\n\n` +
          `  * Generated from infra/pkg/recipes/${r.name}.toml.\n\n` +
          ` -- ${r.maintainer}  ${rfc2822(r.date)}\n`,
      );
      put(
        `${d}/debian/rules`,
        `#!/usr/bin/make -f\n${header(r)}%:\n\tdh $@\n\noverride_dh_auto_install:\n` +
          r.files
            .map((f) => `\tinstall -Dm${mode(f)} files/${basename(f.src)} debian/${r.name}${f.dest}\n`)
            .join(""),
        0o755,
      );
      put(`${d}/debian/source/format`, "3.0 (quilt)\n");
      put(
        `${d}/debian/copyright`,
        `Format: https://www.debian.org/doc/packaging-manuals/copyright-format/1.0/\n` +
          `Upstream-Name: ${r.name}\nSource: ${r.homepage}\n\nFiles: *\nCopyright: Aphrody\n` +
          `License: ${r.license.replace(/ OR /g, " or ")}\n`,
      );
      for (const [n, b] of src) put(`${d}/files/${n}`, b);
      put(
        "build.sh",
        `#!/bin/sh\n${header(r)}set -eu\nexport DEBIAN_FRONTEND=noninteractive\n` +
          `apt-get update -q\napt-get install -y -q --no-install-recommends build-essential debhelper dpkg-dev\n` +
          `cd /w/${d} && dpkg-buildpackage -us -uc -b\n` +
          `apt-get install -y -q /w/${r.name}_${r.version}-${r.release}_all.deb\n` +
          r.files.map((f) => `test -f ${f.dest}\n`).join("") +
          `dpkg -s ${r.name} | head -3\n`,
        0o755,
      );
      break;
    }
    case "alpine": {
      const names = [...src.keys()];
      // abuild names the repository after the parent directory of the APKBUILD: aphrody/<name>/.
      const dir = `aphrody/${r.name}`;
      put(
        `${dir}/APKBUILD`,
        header(r) +
          `# Maintainer: ${r.maintainer}\n` +
          `pkgname=${r.name}\npkgver=${r.version}\npkgrel=${r.release - 1}\n` +
          `pkgdesc="${q(r.summary)}"\nurl="${r.homepage}"\narch="noarch"\nlicense="${r.license}"\n` +
          `depends="${deps.join(" ")}"\noptions="!check"\nsource="${names.join(" ")}"\n\n` +
          `package() {\n` +
          r.files.map((f) => `\tinstall -Dm${mode(f)} "$srcdir"/${basename(f.src)} "$pkgdir"${f.dest}\n`).join("") +
          `}\n\nsha512sums="\n` +
          names.map((n) => `${sha("sha512", src.get(n)!)}  ${n}\n`).join("") +
          `"\n`,
      );
      for (const [n, b] of src) put(`${dir}/${n}`, b);
      put(
        "build.sh",
        `#!/bin/sh\n${header(r)}set -eu\n` +
          `apk add --no-cache alpine-sdk\nabuild-keygen -an\n` +
          `cd /w/${dir} && abuild -F -d -P /w/repo\n` +
          `apk add --no-cache --allow-untrusted $(find /w/repo -name '${r.name}-${r.version}-r${r.release - 1}.apk')\n` +
          r.files.map((f) => `test -f ${f.dest}\n`).join("") +
          `apk info -e ${r.name}\n`,
        0o755,
      );
      break;
    }
    case "portage": {
      const cat = r.portage_category ?? "app-misc";
      const rev = r.release > 1 ? `-r${r.release - 1}` : "";
      const dir = `${cat}/${r.name}`;
      const lines = r.files.map((f) => {
        const n = basename(f.src);
        const exe = mode(f) === "755";
        return `\t${exe ? "exeinto" : "insinto"} ${posix.dirname(f.dest)}\n` +
          (exe ? "" : `\tinsopts -m0${mode(f)}\n`) +
          `\t${exe ? "newexe" : "newins"} "\${FILESDIR}/${n}" ${posix.basename(f.dest)}\n`;
      });
      put(
        `${dir}/${r.name}-${r.version}${rev}.ebuild`,
        `# Copyright ${r.date.slice(0, 4)} Aphrody\n# Distributed under the terms of ${r.license}\n${header(r)}\n` +
          `EAPI=8\n\nDESCRIPTION="${q(r.summary)}"\nHOMEPAGE="${r.homepage}"\nS="\${WORKDIR}"\n\n` +
          `LICENSE="${gentooLicense(r.license)}"\nSLOT="0"\nKEYWORDS="~amd64 ~arm64"\n` +
          `RDEPEND="${deps.join(" ")}"\n\nsrc_install() {\n${lines.join("")}}\n`,
      );
      put(
        `${dir}/metadata.xml`,
        `<?xml version="1.0" encoding="UTF-8"?>\n<!DOCTYPE pkgmetadata SYSTEM "https://www.gentoo.org/dtd/metadata.dtd">\n` +
          `<pkgmetadata>\n\t<maintainer type="person">\n\t\t<email>${r.maintainer.replace(/.*<|>.*/g, "")}</email>\n` +
          `\t\t<name>${r.maintainer.replace(/\s*<.*/, "")}</name>\n\t</maintainer>\n</pkgmetadata>\n`,
      );
      for (const [n, b] of src) put(`${dir}/files/${n}`, b);
      put("build.sh", `#!/bin/sh\n${header(r)}set -eu\nfor f in /w/${dir}/*.ebuild; do bash -n "$f"; done\n`, 0o755);
      break;
    }
    case "soong": {
      const mods = r.files.map((f) => {
        const n = basename(f.src);
        const id = `${r.name}-${n}`.replace(/[^A-Za-z0-9_.-]/g, "_");
        if (mode(f) === "755") return `sh_binary {\n    name: "${id}",\n    src: "${n}",\n    filename: "${posix.basename(f.dest)}",\n}\n`;
        const m = /^\/(?:system\/)?etc\/(.*)$/.exec(posix.dirname(f.dest) + "/");
        if (!m) throw new Error(`${r.name}: ${f.dest} n'a pas d'équivalent Android (/etc ou /system/etc)`);
        const sub = m[1]!.replace(/\/$/, "");
        return `prebuilt_etc {\n    name: "${id}",\n    src: "${n}",\n    filename: "${posix.basename(f.dest)}",\n${sub ? `    sub_dir: "${sub}",\n` : ""}}\n`;
      });
      put("Android.bp", `${header(r, "//")}\n${mods.join("\n")}`);
      for (const [n, b] of src) put(n, b);
      put("build.sh", `#!/bin/sh\n${header(r)}set -eu\ntest -s /w/Android.bp\n`, 0o755);
      break;
    }
    case "nix": {
      const nixDest = (d: string) => d.replace(/^\/usr\//, "/");
      const args = ["lib", "stdenvNoCC", ...deps].join(", ");
      put(
        "default.nix",
        header(r) +
          `{ ${args} }:\n\nstdenvNoCC.mkDerivation {\n  pname = "${r.name}";\n  version = "${r.version}";\n  src = ./files;\n` +
          (deps.length ? `  propagatedBuildInputs = [ ${deps.join(" ")} ];\n` : "") +
          `  dontConfigure = true;\n  dontBuild = true;\n  installPhase = ''\n    runHook preInstall\n` +
          r.files
            .map((f) => `    install -Dm${mode(f)} $src/${basename(f.src)} $out${nixDest(f.dest)}\n`)
            .join("") +
          `    runHook postInstall\n  '';\n  meta = {\n    description = "${q(r.summary)}";\n    homepage = "${r.homepage}";\n` +
          `    license = with lib.licenses; [ ${nixLicenses(r.license)} ];\n    platforms = lib.platforms.linux;\n  };\n}\n`,
      );
      for (const [n, b] of src) put(`files/${n}`, b);
      const flake = distro?.nixpkgs ?? "github:NixOS/nixpkgs/nixos-unstable";
      put(
        "build.sh",
        `#!/bin/sh\n${header(r)}set -eu\n` +
          `nix --extra-experimental-features 'nix-command flakes' build --impure --print-build-logs --option sandbox false -o /w/result \\\n` +
          `  --expr '(builtins.getFlake "${flake}").legacyPackages.x86_64-linux.callPackage /w/default.nix {}'\n` +
          r.files.map((f) => `test -f /w/result${nixDest(f.dest)}\n`).join(""),
        0o755,
      );
      break;
    }
    case "docker": {
      put(
        "Dockerfile",
        `# syntax=docker/dockerfile:1\n${header(r)}# OCI layer of ${r.name}: \`COPY --from=ghcr.io/aphrody-labs/pkg-${r.name}:${r.version} / /\`.\n` +
          `FROM scratch\n` +
          r.files.map((f) => `COPY --chmod=${mode(f)} files/${basename(f.src)} ${f.dest}\n`).join("") +
          `LABEL org.opencontainers.image.title="${r.name}" \\\n` +
          `      org.opencontainers.image.description="${q(r.summary)}" \\\n` +
          `      org.opencontainers.image.version="${r.version}-${r.release}" \\\n` +
          `      org.opencontainers.image.licenses="${r.license}" \\\n` +
          `      org.opencontainers.image.source="https://github.com/aphrody-labs/src"\n`,
      );
      for (const [n, b] of src) put(`files/${n}`, b);
      // Runs on the host (docker CLI), not in a container: build the layer and list its files.
      put(
        "build.sh",
        `#!/bin/sh\n${header(r)}set -eu\ncd "$(dirname "$0")"\n` +
          `docker build -q -t pkg-${r.name}:${r.version}-${r.release} .\n` +
          `cid=$(docker create pkg-${r.name}:${r.version}-${r.release} /none)\n` +
          `docker export "$cid" | tar -t > files.txt\ndocker rm "$cid" >/dev/null\n` +
          r.files.map((f) => `grep -qx '${f.dest.slice(1)}' files.txt\n`).join(""),
        0o755,
      );
      break;
    }
  }
  return out;
}

/** Formats a recipe targets, in FORMATS order. */
export function formatsOf(r: Recipe): Format[] {
  return FORMATS.filter((f) => r.targets.includes(TARGET_OF[f]));
}

/** (recipe, distro) pairs built by CI: distro marked ci and its format targeted by the recipe. */
export function matrix(recipes: Recipe[], distros: Distro[], ciOnly = true) {
  return recipes.flatMap((r) =>
    distros
      .filter((d) => (!ciOnly || d.ci) && r.targets.includes(TARGET_OF[d.format]))
      .map((d) => ({ recipe: r.name, distro: d.name, format: d.format, image: d.image ?? "" })),
  );
}

