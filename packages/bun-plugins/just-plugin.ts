// Sovereign Bun Plugin: Justfile Recipe Importer
import { plugin } from "bun";
import { readFileSync } from "node:fs";

export interface RecipeMeta {
  name: string;
  description: string;
  parameters: string[];
  body: string[];
}

export function parseJustfile(content: string): Record<string, RecipeMeta> {
  const recipes: Record<string, RecipeMeta> = {};
  const lines = content.split(/\r?\n/);
  let currentComment = "";

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const trimmed = line.trim();

    if (trimmed.startsWith("#")) {
      currentComment = currentComment
        ? `${currentComment} ${trimmed.slice(1).trim()}`
        : trimmed.slice(1).trim();
      continue;
    }

    // Match recipe definition: name param1="default" param2:
    const recipeMatch = line.match(/^([a-zA-Z0-9_-]+)(\s+[^:]+)?\s*:/);
    if (recipeMatch) {
      const name = recipeMatch[1];
      const rawParams = (recipeMatch[2] || "").trim();
      const parameters = rawParams
        ? rawParams
            .split(/\s+/)
            .map((p) => p.split("=")[0].trim())
            .filter(Boolean)
        : [];

      const body: string[] = [];
      let j = i + 1;
      while (
        j < lines.length &&
        (lines[j].startsWith("  ") ||
          lines[j].startsWith("\t") ||
          lines[j].trim() === "")
      ) {
        if (lines[j].trim()) {
          body.push(lines[j].trim());
        }
        j++;
      }
      i = j - 1;

      recipes[name] = {
        name,
        description: currentComment || `Executes just ${name}`,
        parameters,
        body,
      };
      currentComment = "";
    } else if (trimmed && !trimmed.startsWith("set ")) {
      currentComment = "";
    }
  }

  return recipes;
}

export function generateJustModule(
  justfilePath: string,
  content: string,
): string {
  const recipes = parseJustfile(content);
  const normalizedPath = justfilePath.replace(/\\/g, "/");

  const recipeExports = Object.entries(recipes)
    .map(([name, meta]) => {
      const safeName = name.replace(/[^a-zA-Z0-9_$]/g, "_");
      const fnName = safeName === "default" ? "run_default" : safeName;
      const exportStmt =
        safeName === "default"
          ? `export { run_default as default };`
          : `export { ${fnName} };`;

      return `
async function ${fnName}(args = {}) {
  const { execSync } = await import("node:child_process");
  const argPairs = Object.entries(args).map(([k, v]) => \`\${k}="\${v}"\`).join(" ");
  const cmd = \`just -f "${normalizedPath}" ${name} \${argPairs}\`;
  try {
    const stdout = execSync(cmd, { encoding: "utf-8", stdio: ["ignore", "pipe", "pipe"] });
    return { exitCode: 0, stdout: stdout.trim(), stderr: "" };
  } catch (err) {
    return { exitCode: err.status || 1, stdout: (err.stdout || "").toString(), stderr: (err.stderr || err.message).toString() };
  }
}
${exportStmt}
`;
    })
    .join("\n");

  return `
// Auto-generated by Sovereign Bun just-plugin
export const justfilePath = ${JSON.stringify(normalizedPath)};
export const recipes = ${JSON.stringify(recipes, null, 2)};
${recipeExports}
`;
}

export const justPlugin = {
  name: "sovereign-just-plugin",
  setup(build: any) {
    build.onLoad(
      { filter: /(\.just|justfile)$/i },
      (args: { path: string }) => {
        const content = readFileSync(args.path, "utf-8");
        const code = generateJustModule(args.path, content);
        return {
          contents: code,
          loader: "js",
        };
      },
    );
  },
};

// Register plugin with Bun runtime
try {
  plugin(justPlugin);
} catch {
  // Ignore re-registration errors in test runs
}
