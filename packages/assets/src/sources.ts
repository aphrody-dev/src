import { createHash } from "node:crypto";
import {
  createWriteStream,
  existsSync,
  mkdirSync,
  renameSync,
  rmSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { type Asset, libraryRoot, loadAll, storeRoot } from "./manifest.ts";
import { hashFile, pool, run } from "./util.ts";

/**
 * Importers turn a public catalog into a pinned `[[pack]]` manifest: they download each file once
 * into the store, check the catalog's own md5 when it publishes one, and record sha256.
 * All catalogs imported here are CC0-1.0 (Poly Haven, ambientCG) or OFL-1.1 (google/fonts ofl/).
 */
export interface Item {
  rel: string;
  url: string;
  md5?: string;
}

export interface PackMeta {
  id_base: string;
  kind: string;
  path_base: string;
  license: string;
  author: string;
  attribution: string;
}

const UA = {
  "user-agent": "aphrody-assets/0.1 (+https://github.com/aphrody-dev/src)",
};

async function getJson<T>(url: string): Promise<T> {
  const r = await fetch(url, { headers: UA });
  if (!r.ok) throw new Error(`${url}: HTTP ${r.status}`);
  return (await r.json()) as T;
}

async function download(
  url: string,
  dest: string,
  md5?: string,
): Promise<string> {
  if (existsSync(dest)) return hashFile(dest);
  mkdirSync(dirname(dest), { recursive: true });
  const part = `${dest}.part`;
  for (let i = 0; ; i++) {
    try {
      const r = await fetch(url, { headers: UA, redirect: "follow" });
      if (!r.ok) throw new Error(`HTTP ${r.status}`);
      const s = createHash("sha256");
      const m = createHash("md5");
      const out = createWriteStream(part);
      for await (const c of r.body as unknown as AsyncIterable<Uint8Array>) {
        s.update(c);
        m.update(c);
        if (!out.write(c)) await new Promise((x) => out.once("drain", x));
      }
      await new Promise((x) => out.end(x));
      if (md5 && m.digest("hex") !== md5)
        throw new Error("md5 mismatch against catalog");
      renameSync(part, dest);
      return s.digest("hex");
    } catch (e) {
      rmSync(part, { force: true });
      if (i >= 2) throw new Error(`${url}: ${String(e)}`);
    }
  }
}

export interface ImportReport {
  pack: string;
  files: number;
  bytes: number;
  failed: number;
  skippedExisting: number;
}

export async function importPack(
  root: string,
  name: string,
  meta: PackMeta,
  items: Item[],
  opts: { jobs?: number } = {},
): Promise<ImportReport> {
  const known = new Set((await loadAll(root)).map((a: Asset) => a.path));
  const store = storeRoot(root);
  const lines: string[] = [];
  const rep: ImportReport = {
    pack: name,
    files: 0,
    bytes: 0,
    failed: 0,
    skippedExisting: 0,
  };
  await pool(items, opts.jobs ?? 8, async (it) => {
    const path = `${meta.path_base}${it.rel}`;
    if (known.has(path)) {
      rep.skippedExisting++;
      return;
    }
    try {
      const sha = await download(it.url, join(store, path), it.md5);
      lines[items.indexOf(it)] = `${it.rel}|${sha}|${it.url}`;
      rep.files++;
      rep.bytes += Bun.file(join(store, path)).size;
    } catch (e) {
      rep.failed++;
      console.error(String(e));
    }
  });
  const body = lines.filter(Boolean);
  if (body.length) {
    const toml =
      `# Generated by \`ay assets import ${name}\`. files = ["relative path|sha256|url"].\n\n[[pack]]\n` +
      Object.entries(meta)
        .map(([k, v]) => `${k} = ${JSON.stringify(v)}`)
        .join("\n") +
      `\nstorage = "remote"\nfiles = [\n${body.map((l) => `  ${JSON.stringify(l)},`).join("\n")}\n]\n`;
    await Bun.write(join(libraryRoot(root), `manifest.${name}.toml`), toml);
  }
  return rep;
}

type PHFiles = Record<
  string,
  Record<
    string,
    Record<
      string,
      {
        url: string;
        md5: string;
        include?: Record<string, { url: string; md5: string }>;
      }
    >
  >
>;

export async function polyhavenItems(
  type: "textures" | "hdris" | "models",
  limit: number,
  res = "1k",
): Promise<Item[]> {
  const list = Object.keys(
    await getJson<Record<string, unknown>>(
      `https://api.polyhaven.com/assets?t=${type}`,
    ),
  )
    .sort()
    .slice(0, limit);
  const out: Item[] = [];
  await pool(list, 8, async (slug) => {
    const f = await getJson<PHFiles>(`https://api.polyhaven.com/files/${slug}`);
    if (type === "textures") {
      for (const map of [
        "Diffuse",
        "nor_gl",
        "Rough",
        "Displacement",
        "AO",
        "arm",
      ]) {
        const e = f[map]?.[res]?.jpg;
        if (e)
          out.push({
            rel: `${slug}/${e.url.split("/").pop()}`,
            url: e.url,
            md5: e.md5,
          });
      }
    } else if (type === "hdris") {
      const e = (f as unknown as { hdri?: PHFiles[string] }).hdri?.[res]?.hdr;
      if (e)
        out.push({
          rel: `${slug}/${e.url.split("/").pop()}`,
          url: e.url,
          md5: e.md5,
        });
    } else {
      const e = (f as unknown as { gltf?: PHFiles[string] }).gltf?.[res]?.gltf;
      if (e) {
        out.push({
          rel: `${slug}/${e.url.split("/").pop()}`,
          url: e.url,
          md5: e.md5,
        });
        for (const [p, inc] of Object.entries(e.include ?? {}))
          out.push({ rel: `${slug}/${p}`, url: inc.url, md5: inc.md5 });
      }
    }
  });
  return out.sort((a, b) => (a.rel < b.rel ? -1 : 1));
}

export async function ambientcgItems(
  limit: number,
  attr = "1K-JPG",
): Promise<Item[]> {
  const out: Item[] = [];
  for (let off = 0; out.length < limit; off += 100) {
    const j = await getJson<{
      foundAssets: {
        assetId: string;
        downloadFolders: Record<
          string,
          {
            downloadFiletypeCategories: Record<
              string,
              {
                downloads: {
                  attribute: string;
                  downloadLink: string;
                  fileName: string;
                }[];
              }
            >;
          }
        >;
      }[];
    }>(
      `https://ambientcg.com/api/v2/full_json?type=Material&sort=Alphabet&limit=100&offset=${off}&include=downloadData`,
    );
    if (!j.foundAssets.length) break;
    for (const a of j.foundAssets) {
      const d = Object.values(a.downloadFolders)
        .flatMap((x) =>
          Object.values(x.downloadFiletypeCategories).flatMap(
            (c) => c.downloads,
          ),
        )
        .find((x) => x.attribute === attr);
      if (d) out.push({ rel: d.fileName, url: d.downloadLink });
    }
  }
  return out.slice(0, limit);
}

/** google/fonts `ofl/`: every file of a family folder is covered by that family's OFL.txt. */
export async function fontItems(
  limit: number,
): Promise<{ items: Item[]; sha: string }> {
  const gh = async <T>(p: string) => {
    const r = await run(["gh", "api", p]);
    if (!r.ok) throw new Error(`gh api ${p}: ${r.err.trim().slice(0, 200)}`);
    return JSON.parse(r.out) as T;
  };
  const sha = (await gh<{ sha: string }>("repos/google/fonts/commits/main"))
    .sha;
  const fam = (
    await gh<{ name: string; type: string }[]>(
      `repos/google/fonts/contents/ofl?ref=${sha}`,
    )
  )
    .filter((x) => x.type === "dir")
    .slice(0, limit);
  const out: Item[] = [];
  await pool(fam, 6, async (f) => {
    const files = await gh<{ name: string; size: number }[]>(
      `repos/google/fonts/contents/ofl/${f.name}?ref=${sha}`,
    );
    for (const x of files)
      if (/\.ttf$/i.test(x.name) && x.size < 1_500_000)
        out.push({
          rel: `${f.name}/${x.name}`,
          url: `https://raw.githubusercontent.com/google/fonts/${sha}/ofl/${f.name}/${encodeURIComponent(x.name)}`,
        });
  });
  return { items: out.sort((a, b) => (a.rel < b.rel ? -1 : 1)), sha };
}

