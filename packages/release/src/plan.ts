// Pure parts of `ay release`: owner approval gate, vcpkg git-registry layout, CMake package config.
// Registry formats: learn.microsoft.com/vcpkg/maintainers/registries (git registries: versions/baseline.json with a
// "default" baseline, versions/<first letter>-/<port>.json entries { git-tree, version, port-version }).

export type Registry = "crates" | "npm" | "pypi" | "vcpkg" | "github";

export interface Item {
  registry: Registry;
  name: string;
  version: string;
  /** true when the package does not exist at all on the registry (first publish). */
  isNew: boolean;
  /** this exact version is already there: nothing to publish. */
  published: boolean;
  dryRun?: { ok: boolean; detail: string };
}

/** `.agents/owner-rules.json`: { "release": { "approve_new": ["crates:name", "npm:@scope/x", "pypi:x", "vcpkg:port", "vcpkg:repo"] } } */
export interface OwnerRules {
  release?: { approve_new?: string[]; approved_by?: string; date?: string };
}

export const key = (i: Pick<Item, "registry" | "name">) =>
  `${i.registry}:${i.name}`;

/** New packages need an explicit owner entry; new versions of existing packages do not. */
export function gate(
  items: Item[],
  rules: OwnerRules | null,
): { blocked: string[]; reason: string | null } {
  const fresh = items.filter((i) => i.isNew && !i.published).map(key);
  if (!fresh.length) return { blocked: [], reason: null };
  if (!rules)
    return {
      blocked: fresh,
      reason:
        ".agents/owner-rules.json absent: new packages stop at the dry-run",
    };
  const ok = new Set(rules.release?.approve_new ?? []);
  const blocked = fresh.filter((k) => !ok.has(k));
  return {
    blocked,
    reason: blocked.length
      ? "not listed in .agents/owner-rules.json release.approve_new"
      : null,
  };
}

export interface PortSpec {
  crate: string;
  port: string;
  lib: string;
  header: string;
  target: string;
}

export interface PortSource {
  repo: string;
  ref: string;
  /** SHA512 of https://github.com/<repo>/archive/<ref>.tar.gz; null in a dry-run before the tag exists. */
  sha512: string | null;
  description: string;
  license: string;
}

const cmakeId = (port: string) => port.replace(/[^A-Za-z0-9_]/g, "_");

/** Files of ports/<port>/: vcpkg.json, portfile.cmake (cargo build of the C ABI crate), CMake config, usage. */
export function portFiles(
  p: PortSpec,
  version: string,
  src: PortSource,
): Record<string, string> {
  const [ns, short] = p.target.split("::") as [string, string];
  const manifest = {
    name: p.port,
    version,
    description: src.description,
    homepage: `https://github.com/${src.repo}`,
    license: src.license,
    supports: "!uwp & !(arm & windows)",
    dependencies: [{ name: "vcpkg-cmake-config", host: true }],
  };
  const portfile = `# Generated by ay release (packages/release). Builds the C ABI crate ${p.crate} with the host cargo.
vcpkg_from_github(
    OUT_SOURCE_PATH SOURCE_PATH
    REPO ${src.repo}
    REF ${src.ref}
    SHA512 ${src.sha512 ?? "0"}
    HEAD_REF main
)
find_program(CARGO cargo REQUIRED)
set(profile release)
if(VCPKG_TARGET_IS_WINDOWS)
    set(dyn "${p.lib}.dll") ; set(imp "${p.lib}.dll.lib") ; set(sta "${p.lib}.lib")
elseif(VCPKG_TARGET_IS_OSX)
    set(dyn "lib${p.lib}.dylib") ; set(sta "lib${p.lib}.a")
else()
    set(dyn "lib${p.lib}.so") ; set(sta "lib${p.lib}.a")
endif()
vcpkg_execute_build_process(
    COMMAND "\${CARGO}" build --locked --release -p ${p.port} --target-dir "\${CURRENT_BUILDTREES_DIR}/target"
    WORKING_DIRECTORY "\${SOURCE_PATH}"
    LOGNAME cargo-\${TARGET_TRIPLET}
)
set(out "\${CURRENT_BUILDTREES_DIR}/target/\${profile}")
file(INSTALL "\${SOURCE_PATH}/${p.crate}/${p.header}" DESTINATION "\${CURRENT_PACKAGES_DIR}/include")
if(VCPKG_LIBRARY_LINKAGE STREQUAL "dynamic")
    if(VCPKG_TARGET_IS_WINDOWS)
        file(INSTALL "\${out}/\${dyn}" DESTINATION "\${CURRENT_PACKAGES_DIR}/bin")
        file(INSTALL "\${out}/\${imp}" DESTINATION "\${CURRENT_PACKAGES_DIR}/lib")
    else()
        file(INSTALL "\${out}/\${dyn}" DESTINATION "\${CURRENT_PACKAGES_DIR}/lib")
    endif()
else()
    file(INSTALL "\${out}/\${sta}" DESTINATION "\${CURRENT_PACKAGES_DIR}/lib")
endif()
file(INSTALL "\${CMAKE_CURRENT_LIST_DIR}/${p.port}-config.cmake" DESTINATION "\${CURRENT_PACKAGES_DIR}/share/${p.port}")
set(VCPKG_POLICY_SKIP_ABSOLUTE_PATHS_CHECK enabled)
set(VCPKG_POLICY_MISMATCHED_NUMBER_OF_BINARIES enabled)
file(INSTALL "\${CMAKE_CURRENT_LIST_DIR}/usage" DESTINATION "\${CURRENT_PACKAGES_DIR}/share/\${PORT}")
vcpkg_install_copyright(FILE_LIST "\${SOURCE_PATH}/LICENSE-MIT" "\${SOURCE_PATH}/LICENSE-APACHE")
`;
  const id = cmakeId(p.port);
  const config = `# CMake package config of ${p.port} (find_package(${p.port} CONFIG REQUIRED)), generated by ay release.
include_guard(GLOBAL)
get_filename_component(_${id}_prefix "\${CMAKE_CURRENT_LIST_DIR}/../.." ABSOLUTE)
find_library(_${id}_lib NAMES ${p.lib} ${p.lib}.dll PATHS "\${_${id}_prefix}/lib" NO_DEFAULT_PATH REQUIRED)
if(NOT TARGET ${p.target})
    add_library(${p.target} UNKNOWN IMPORTED)
    set_target_properties(${p.target} PROPERTIES
        IMPORTED_LOCATION "\${_${id}_lib}"
        INTERFACE_INCLUDE_DIRECTORIES "\${_${id}_prefix}/include")
    if(UNIX AND NOT APPLE)
        set_property(TARGET ${p.target} APPEND PROPERTY INTERFACE_LINK_LIBRARIES dl pthread m)
    endif()
endif()
set(${p.port}_FOUND TRUE)
set(${p.port}_VERSION ${version})
`;
  const usage = `${p.port} provides CMake targets:

    find_package(${p.port} CONFIG REQUIRED)
    target_link_libraries(main PRIVATE ${ns}::${short})
`;
  return {
    "vcpkg.json": JSON.stringify(manifest, null, 2) + "\n",
    "portfile.cmake": portfile,
    [`${p.port}-config.cmake`]: config,
    usage,
  };
}

export interface VersionEntry {
  "git-tree": string;
  version: string;
  "port-version": number;
}

/** versions/<l>-/<port>.json: newest first, an existing (version, port-version) is replaced, not duplicated. */
export function versionsFile(
  prev: { versions: VersionEntry[] } | null,
  e: VersionEntry,
): { versions: VersionEntry[] } {
  const rest = (prev?.versions ?? []).filter(
    (v) =>
      !(v.version === e.version && v["port-version"] === e["port-version"]),
  );
  return { versions: [e, ...rest] };
}

export type Baseline = Record<
  string,
  Record<string, { baseline: string; "port-version": number }>
>;

export function baseline(
  prev: Baseline | null,
  port: string,
  version: string,
  portVersion = 0,
): Baseline {
  const b: Baseline = { default: {}, ...(prev ?? {}) };
  b.default = {
    ...b.default,
    [port]: { baseline: version, "port-version": portVersion },
  };
  return b;
}

export const versionsPath = (port: string) =>
  `versions/${port[0]}-/${port}.json`;

/** pyproject.toml for a PyO3 crate without one (maturin backend, abi3 wheel). */
export function pyproject(
  dist: string,
  version: string,
  description: string,
  repo: string,
): string {
  return `[build-system]
requires = ["maturin>=1.16,<2"]
build-backend = "maturin"

[project]
name = "${dist}"
version = "${version}"
description = "${description.replace(/"/g, "'")}"
requires-python = ">=3.10"
license = "MIT OR Apache-2.0"
urls = { Repository = "https://github.com/${repo}" }

[tool.maturin]
features = ["pyo3/extension-module"]
`;
}
