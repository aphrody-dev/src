export function generateHereticConfigToml(opts: {
  modelRepo: string;
  mode: "uncensor" | "noslop" | "nosyco" | "terse";
  bnb4bit?: boolean;
}): string {
  const modeDescriptions: Record<typeof opts.mode, string> = {
    uncensor: "refusal_suppression",
    noslop: "slop_suppression",
    nosyco: "sycophancy_suppression",
    terse: "concise_alignment",
  };
  return [
    "# Generated by pi-opencode for p-e-w/heretic v2 (C:\\src\\third_party\\heretic)",
    `model = "${opts.modelRepo}"`,
    `quantization = "${opts.bnb4bit !== false ? "bnb_4bit" : "none"}"`,
    `steering_profile = "${modeDescriptions[opts.mode]}"`,
    "preserve_mmlu_kl_threshold = 0.035",
    'device = "cuda:0"',
    "",
  ].join("\n");
}

export async function probeActiveLocalEngines(
  timeoutMs = 350,
): Promise<
  Array<{ endpoint: LocalEngineEndpoint; healthy: boolean; latencyMs: number }>
> {
  const results = await Promise.all(
    LOCAL_ENGINE_ENDPOINTS.map(async (ep) => {
      const start = performance.now();
      const probeUrl =
        ep.protocol === "ring3-native"
          ? `${ep.baseUrl}/ok`
          : `${ep.baseUrl}/models`;
      try {
        const res = await fetch(probeUrl, {
          signal: AbortSignal.timeout(timeoutMs),
        });
        return {
          endpoint: ep,
          healthy: res.ok || res.status === 401, // LU Local API returns 401 when token-gated & alive
          latencyMs: Math.round((performance.now() - start) * 100) / 100,
        };
      } catch {
        return {
          endpoint: ep,
          healthy: false,
          latencyMs: Math.round((performance.now() - start) * 100) / 100,
        };
      }
    }),
  );
  return results;
}

export interface LocalProviderConfig {
  baseUrl: string;
  apiKey?: string;
  model: string;
  temperature?: number;
  topP?: number;
  maxTokens?: number;
}

/**
 * Calls any OpenAI-compatible local uncensored endpoint (`Locally Uncensored :8129`,
 * `ring3-agent /v1/chat/completions`, `mistral.rs`, `llama.cpp`, `Ollama`) with zero
 * client-side prompt filtering or cloud telemetry.
 */
export async function callLocalUncensoredModel(
  cfg: LocalProviderConfig,
  messages: PiMessage[],
  tools: typeof PI_ATOMIC_TOOL_DECLARATIONS,
): Promise<{ content: string; toolCalls?: PiToolCall[] }> {
  const endpoint = cfg.baseUrl.endsWith("/chat/completions")
    ? cfg.baseUrl
    : `${cfg.baseUrl.replace(/\/$/, "")}/chat/completions`;

  const openAiMessages = messages.map((m) => {
    if (m.role === "tool") {
      return {
        role: "tool",
        tool_call_id: m.toolCallId ?? "call_0",
        content: m.content,
      };
    }
    if (m.role === "assistant" && m.toolCalls?.length) {
      return {
        role: "assistant",
        content: m.content || null,
        tool_calls: m.toolCalls.map((tc) => ({
          id: tc.id,
          type: "function",
          function: {
            name: tc.name,
            arguments: JSON.stringify(tc.arguments),
          },
        })),
      };
    }
    return { role: m.role, content: m.content };
  });

  const payload = {
    model: cfg.model,
    messages: openAiMessages,
    temperature: cfg.temperature ?? 0.2,
    top_p: cfg.topP ?? 0.95,
    max_tokens: cfg.maxTokens ?? 4096,
    tools: tools.map((t) => ({
      type: "function",
      function: {
        name: t.name,
        description: t.description,
        parameters: t.parameters,
      },
    })),
  };

  const headers: Record<string, string> = {
    "content-type": "application/json",
  };
  if (cfg.apiKey) {
    headers.authorization = `Bearer ${cfg.apiKey}`;
  }

  const res = await fetch(endpoint, {
    method: "POST",
    headers,
    body: JSON.stringify(payload),
  });
  if (!res.ok) {
    throw new Error(
      `Local uncensored model HTTP ${res.status}: ${await res.text()}`,
    );
  }
  const data = (await res.json()) as {
    choices?: Array<{
      message?: {
        content?: string | null;
        tool_calls?: Array<{
          id: string;
          function: { name: string; arguments: string };
        }>;
      };
    }>;
  };

  const msg = data.choices?.[0]?.message;
  const parsedCalls: PiToolCall[] = [];
  for (const rawTc of msg?.tool_calls ?? []) {
    if (
      rawTc.function.name === "read" ||
      rawTc.function.name === "write" ||
      rawTc.function.name === "edit" ||
      rawTc.function.name === "bash"
    ) {
      let args: Record<string, unknown> = {};
      try {
        args = JSON.parse(rawTc.function.arguments || "{}") as Record<
          string,
          unknown
        >;
      } catch {
        args = {};
      }
      parsedCalls.push({
        id: rawTc.id,
        name: rawTc.function.name,
        arguments: args,
      });
    }
  }

  return {
    content: msg?.content ?? "",
    toolCalls: parsedCalls.length > 0 ? parsedCalls : undefined,
  };
}
