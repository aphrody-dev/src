// ValidateNodePlacement enforces sovereign policy:
// Node `usa` (72.60.186.43 / 10.200.77.5) is strictly restricted to Google/Gemini API egress workloads.
// Any general workload attempting to deploy to `usa` without GoogleEgress=true or RegionUSGoogleEgress is rejected!
func ValidateNodePlacement(spec *detect.ProjectSpec, nodeID string) error {
	topology := FleetTopology()
	node, ok := topology[nodeID]
	if !ok {
		return fmt.Errorf("unknown fleet node %q (valid: fr1, fr2, usa)", nodeID)
	}
	if node.ID == "usa" {
		if !spec.GoogleEgress && spec.Region != detect.RegionUSGoogleEgress {
			return fmt.Errorf(
				"policy violation: workload %q (region=%s, googleEgress=%v) rejected on node 'usa' (72.60.186.43 / 10.200.77.5): node 'usa' is strictly reserved for Google/Gemini API egress proxy workloads",
				spec.Name, spec.Region, spec.GoogleEgress,
			)
		}
	}
	return nil
}

// ValidateProjectPlacement validates all target nodes declared on a ProjectSpec.
func ValidateProjectPlacement(spec *detect.ProjectSpec) error {
	if len(spec.TargetNodes) == 0 {
		return fmt.Errorf("project %q has no targetNodes", spec.Name)
	}
	for _, n := range spec.TargetNodes {
		if err := ValidateNodePlacement(spec, n); err != nil {
			return err
		}
	}
	return nil
}

// GenerateCaddyfile generates a deterministic production HTTP/3 QUIC + Let's Encrypt TLS + Blue/Green health-checked Caddyfile.
func GenerateCaddyfile(specs []*detect.ProjectSpec) string {
	sorted := make([]*detect.ProjectSpec, len(specs))
	copy(sorted, specs)
	sort.Slice(sorted, func(i, j int) bool {
		return sorted[i].Name < sorted[j].Name
	})

	var sb strings.Builder
	sb.WriteString("# =============================================================================\n")
	sb.WriteString("# Sovereign Production Caddyfile (Generated by src-deploy Go 1.27 Engine)\n")
	sb.WriteString("# Automatic Let's Encrypt TLS 1.3 + HTTP/3 QUIC + Zero-Downtime Blue/Green\n")
	sb.WriteString("# Fleet Mesh: fr1 (10.200.77.1), fr2 (10.200.77.3), usa (10.200.77.5 Google-only)\n")
	sb.WriteString("# =============================================================================\n\n")

	sb.WriteString("{\n")
	sb.WriteString("\tadmin 127.0.0.1:2019\n")
	sb.WriteString("\temail ops@aphrody.com\n")
	sb.WriteString("\tservers {\n")
	sb.WriteString("\t\tprotocols h1 h2 h3\n")
	sb.WriteString("\t\ttrusted_proxies static 10.200.77.0/24 173.245.48.0/20 103.21.244.0/22 103.22.200.0/22 103.31.4.0/22 141.101.64.0/18 108.162.192.0/18 190.93.240.0/20 188.114.96.0/20 197.234.240.0/22 198.41.128.0/17 162.158.0.0/15 104.16.0.0/13 104.24.0.0/14 172.64.0.0/13 131.0.72.0/22\n")
	sb.WriteString("\t}\n")
	sb.WriteString("}\n\n")

	// Common security headers snippet
	sb.WriteString("(sovereign_headers) {\n")
	sb.WriteString("\theader {\n")
	sb.WriteString("\t\tStrict-Transport-Security \"max-age=63072000; includeSubDomains; preload\"\n")
	sb.WriteString("\t\tX-Content-Type-Options \"nosniff\"\n")
	sb.WriteString("\t\tX-Frame-Options \"SAMEORIGIN\"\n")
	sb.WriteString("\t\tReferrer-Policy \"strict-origin-when-cross-origin\"\n")
	sb.WriteString("\t\tAlt-Svc 'h3=\":443\"; ma=86400'\n")
	sb.WriteString("\t\t-Server\n")
	sb.WriteString("\t}\n")
	sb.WriteString("\tencode zstd gzip\n")
	sb.WriteString("}\n\n")

	for _, s := range sorted {
		if len(s.Domains) == 0 {
			continue
		}
		isInternal := true
		for _, d := range s.Domains {
			if !strings.Contains(d, ".internal.") {
				isInternal = false
				break
			}
		}

		sb.WriteString(fmt.Sprintf("# Service: %s | Runtime: %s | Region: %s | Nodes: %s\n",
			s.Name, s.Runtime, s.Region, strings.Join(s.TargetNodes, ",")))
		sb.WriteString(strings.Join(s.Domains, ", ") + " {\n")
		if isInternal {
			sb.WriteString("\ttls internal\n")
		}
		sb.WriteString("\timport sovereign_headers\n")

		// Blue/Green upstreams across local node + HA mesh replica
		upstreams := fmt.Sprintf("127.0.0.1:%d 127.0.0.1:%d", s.BluePort, s.GreenPort)
		if containsStr(s.TargetNodes, "fr1") && containsStr(s.TargetNodes, "fr2") {
			upstreams += fmt.Sprintf(" 10.200.77.3:%d", s.BluePort)
		}

		sb.WriteString(fmt.Sprintf("\treverse_proxy %s {\n", upstreams))
		sb.WriteString("\t\tlb_policy first\n")
		sb.WriteString("\t\tlb_try_duration 3s\n")
		sb.WriteString("\t\thealth_uri /healthz\n")
		sb.WriteString("\t\thealth_interval 5s\n")
		sb.WriteString("\t\thealth_timeout 2s\n")
		sb.WriteString("\t\tfail_duration 15s\n")
		sb.WriteString("\t}\n")
		sb.WriteString("}\n\n")
	}

	// Dedicated strict US Google/Gemini Egress Proxy block bound exclusively to Mesh IP on `usa` (10.200.77.5)
	sb.WriteString("# Dedicated US Google/Gemini API Egress Forwarder (usa: 10.200.77.5:9443)\n")
	sb.WriteString("http://10.200.77.5:9443 {\n")
	sb.WriteString("\t@google_api header_regexp host Host ^(generativelanguage\\.googleapis\\.com|aiplatform\\.googleapis\\.com|oauth2\\.googleapis\\.com|www\\.googleapis\\.com)$\n")
	sb.WriteString("\thandle @google_api {\n")
	sb.WriteString("\t\treverse_proxy https://generativelanguage.googleapis.com {\n")
	sb.WriteString("\t\t\theader_up Host {http.request.host}\n")
	sb.WriteString("\t\t}\n")
	sb.WriteString("\t}\n")
	sb.WriteString("\thandle {\n")
	sb.WriteString("\t\trespond \"Forbidden: usa node strictly allows Google/Gemini API egress only\" 403\n")
	sb.WriteString("\t}\n")
	sb.WriteString("}\n")

	return sb.String()
}

// GenerateSystemdUnit produces a hardened systemd template unit (`sovereign-<app>@.service` for `@blue` and `@green` instances).
func GenerateSystemdUnit(spec *detect.ProjectSpec, memoryMax string) string {
	if memoryMax == "" {
		memoryMax = "1G"
	}
	var sb strings.Builder
	sb.WriteString(fmt.Sprintf("# Hardened systemd unit for %s (Blue/Green template: @blue -> %d, @green -> %d)\n",
		spec.Name, spec.BluePort, spec.GreenPort))
	sb.WriteString("[Unit]\n")
	sb.WriteString(fmt.Sprintf("Description=Sovereign Service %s (%%i slot)\n", spec.Name))
	sb.WriteString("After=network-online.target wireguard-wg0.service\n")
	sb.WriteString("Wants=network-online.target\n\n")

	sb.WriteString("[Service]\n")
	sb.WriteString("Type=simple\n")
	sb.WriteString("DynamicUser=yes\n")
	sb.WriteString(fmt.Sprintf("StateDirectory=sovereign/%s-%%i\n", spec.Name))
	sb.WriteString(fmt.Sprintf("WorkingDirectory=/opt/sovereign/%s/current-%%i\n", spec.Name))
	sb.WriteString(fmt.Sprintf("EnvironmentFile=-/etc/sovereign/%s.env\n", spec.Name))
	sb.WriteString(fmt.Sprintf("EnvironmentFile=-/etc/sovereign/%s-%%i.port.env\n", spec.Name))
	sb.WriteString(fmt.Sprintf("ExecStart=/opt/sovereign/%s/current-%%i/%s\n", spec.Name, spec.Name))
	sb.WriteString("Restart=always\n")
	sb.WriteString("RestartSec=2s\n")
	sb.WriteString(fmt.Sprintf("MemoryMax=%s\n", memoryMax))
	sb.WriteString("NoNewPrivileges=yes\n")
	sb.WriteString("ProtectSystem=strict\n")
	sb.WriteString("ProtectHome=yes\n")
	sb.WriteString("PrivateTmp=yes\n")
	sb.WriteString("ProtectKernelTunables=yes\n")
	sb.WriteString("ProtectControlGroups=yes\n")
	sb.WriteString("RestrictSUIDSGID=yes\n")
	sb.WriteString("LimitNOFILE=65535\n\n")

	sb.WriteString("[Install]\n")
	sb.WriteString("WantedBy=multi-user.target\n")
	return sb.String()
}

// WriteGeneratedFleetArtifacts writes the complete production Caddyfile and per-service systemd units to outDir.
func WriteGeneratedFleetArtifacts(specs []*detect.ProjectSpec, outDir string) ([]string, error) {
	if err := os.MkdirAll(filepath.Join(outDir, "systemd"), 0o755); err != nil {
		return nil, err
	}
	var written []string

	caddyPath := filepath.Join(outDir, "Caddyfile")
	if err := os.WriteFile(caddyPath, []byte(GenerateCaddyfile(specs)), 0o644); err != nil {
		return nil, err
	}
	written = append(written, filepath.ToSlash(caddyPath))

	for _, s := range specs {
		unitName := fmt.Sprintf("sovereign-%s@.service", s.Name)
		unitPath := filepath.Join(outDir, "systemd", unitName)
		mem := "1G"
		if s.Name == "ring3-agent" || s.Name == "ai-os" {
			mem = "4G"
		}
		if err := os.WriteFile(unitPath, []byte(GenerateSystemdUnit(s, mem)), 0o644); err != nil {
			return nil, err
		}
		written = append(written, filepath.ToSlash(unitPath))
	}
	return written, nil
}

// RolloutStep represents a single atomic SSH/SCP command in a zero-downtime Blue/Green rollout.
type RolloutStep struct {
	Node    string   `json:"node"`
	Program string   `json:"program"`
	Args    []string `json:"args"`
}

// PlanBlueGreenRollout validates node placement and builds atomic SCP + SSH rollout commands.
func PlanBlueGreenRollout(spec *detect.ProjectSpec, localArtifactPath, slot string) ([]RolloutStep, error) {
	if err := ValidateProjectPlacement(spec); err != nil {
		return nil, err
	}
	if slot != "blue" && slot != "green" {
		slot = "blue"
	}
	port := spec.BluePort
	if slot == "green" {
		port = spec.GreenPort
	}
	topology := FleetTopology()
	var steps []RolloutStep
	for _, nodeID := range spec.TargetNodes {
		node := topology[nodeID]
		remoteHost := fmt.Sprintf("%s@%s", node.SSHUser, node.MeshIP)
		remoteStage := fmt.Sprintf("/opt/sovereign/%s/releases/%s-%s", spec.Name, spec.Name, slot)
		remoteLink := fmt.Sprintf("/opt/sovereign/%s/current-%s/%s", spec.Name, slot, spec.Name)

		steps = append(steps,
			RolloutStep{
				Node:    nodeID,
				Program: "ssh",
				Args: []string{
					"-o", "BatchMode=yes",
					"-o", "StrictHostKeyChecking=accept-new",
					remoteHost,
					fmt.Sprintf("sudo mkdir -p /opt/sovereign/%s/releases /opt/sovereign/%s/current-%s /etc/sovereign", spec.Name, spec.Name, slot),
				},
			},
			RolloutStep{
				Node:    nodeID,
				Program: "scp",
				Args: []string{
					"-q",
					filepath.ToSlash(localArtifactPath),
					fmt.Sprintf("%s:%s", remoteHost, remoteStage),
				},
			},
			RolloutStep{
				Node:    nodeID,
				Program: "ssh",
				Args: []string{
					"-o", "BatchMode=yes",
					remoteHost,
					fmt.Sprintf(
						"sudo chmod 0755 %s && sudo ln -sfn %s %s && printf 'PORT=%d\\n' | sudo tee /etc/sovereign/%s-%s.port.env >/dev/null && sudo systemctl restart sovereign-%s@%s.service && sudo caddy reload --config /etc/caddy/Caddyfile",
						remoteStage, remoteStage, remoteLink, port, spec.Name, slot, spec.Name, slot,
					),
				},
			},
		)
	}
	return steps, nil
}

// ExecuteRollout executes (or dry-runs) the planned Blue/Green rollout steps.
func ExecuteRollout(ctx context.Context, steps []RolloutStep, dryRun bool) ([]string, error) {
	logs := make([]string, 0, len(steps))
	for _, st := range steps {
		cmdLine := fmt.Sprintf("[%s] %s %s", st.Node, st.Program, strings.Join(st.Args, " "))
		if dryRun {
			logs = append(logs, "[DRY-RUN] "+cmdLine)
			continue
		}
		cmd := exec.CommandContext(ctx, st.Program, st.Args...)
		out, err := cmd.CombinedOutput()
		if err != nil {
			return logs, fmt.Errorf("rollout failed on %s: %w (%s)", st.Node, err, strings.TrimSpace(string(out)))
		}
		logs = append(logs, "[LIVE] "+cmdLine)
	}
	return logs, nil
}

func containsStr(slice []string, target string) bool {
	for _, item := range slice {
		if item == target {
			return true
		}
	}
	return false
}
