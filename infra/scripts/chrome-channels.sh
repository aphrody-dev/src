#!/usr/bin/env sh
# Track Chrome Stable/Beta/Dev/Canary: Chromium version, V8 version, and the pinned
# revisions of first- and third-party deps read from the DEPS file of each release tag.
# Writes third_party/chrome-channels.toml. Sources: chromiumdash (versions), gitiles (DEPS).
# Usage: scripts/chrome-channels.sh [platform]   (default: Linux)
set -eu
root="$(cd "$(dirname "$0")/../.." && pwd)"
platform="${1:-Linux}"
out="$root/third_party/chrome-channels.toml"
ua="aphrody-labs-chrome-channels"
deps_keys="v8_revision skia_revision angle_revision dawn_revision pdfium_revision boringssl_revision devtools_frontend_revision harfbuzz_revision freetype_revision perfetto_revision catapult_revision"
tmp="$(mktemp)"
{
  echo "# Generated by scripts/chrome-channels.sh on $(date -u +%Y-%m-%dT%H:%MZ). Platform: $platform."
  for ch in Stable Beta Dev Canary; do
    ver="$(curl -fsS -A "$ua" "https://chromiumdash.appspot.com/fetch_releases?channel=$ch&platform=$platform&num=1" \
      | sed -n 's/.*"version":"\([0-9.]*\)".*/\1/p' | head -1)"
    [ -n "$ver" ] || { echo "# $ch: no release found"; continue; }
    curl -fsS -A "$ua" "https://chromium.googlesource.com/chromium/src/+/refs/tags/$ver/DEPS?format=TEXT" | base64 -d > "$tmp"
    v8rev="$(sed -n "s/.*'v8_revision': '\([0-9a-f]*\)'.*/\1/p" "$tmp" | head -1)"
    v8ver=""
    if [ -n "$v8rev" ]; then
      v8ver="$(curl -fsS -A "$ua" "https://chromium.googlesource.com/v8/v8/+/$v8rev/include/v8-version.h?format=TEXT" | base64 -d \
        | awk '/define V8_(MAJOR|MINOR)_VERSION|define V8_BUILD_NUMBER|define V8_PATCH_LEVEL/{printf "%s.", $3}' | sed 's/\.$//')"
    fi
    echo
    echo "[channel.$(echo "$ch" | tr 'A-Z' 'a-z')]"
    echo "chromium = \"$ver\""
    echo "v8 = \"$v8ver\""
    gt() { curl -fsS -A "$ua" "https://chromium.googlesource.com/chromium/src/+/refs/tags/$ver/$1?format=TEXT" | base64 -d; }
    clang="$(gt tools/clang/scripts/update.py | sed -n "s/^CLANG_REVISION = '\([^']*\)'.*/\1/p" | head -1)"
    rust="$(gt tools/rust/update_rust.py | sed -n "s/^RUST_REVISION = '\([^']*\)'.*/\1/p" | head -1)"
    [ -n "$clang" ] && echo "clang = \"$clang\""
    [ -n "$rust" ] && echo "rust = \"$rust\""
    for k in $deps_keys; do
      v="$(sed -n "s/.*'$k': *'\([^']*\)'.*/\1/p" "$tmp" | head -1)"
      [ -n "$v" ] && echo "$k = \"$v\""
    done
  done
} > "$out"
rm -f "$tmp"
cat "$out"
