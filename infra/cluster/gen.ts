// Generates the cluster data plane from infra/deploy.toml [cluster] (single source).
// Output: infra/cluster/generated/<member>/{haproxy.cfg,nginx-cluster.conf,aphrody-cluster.slice}, generated/ssh/*. Usage: bun infra/cluster/gen.ts
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

type Check = { path: string; host: string; expect: string };
type Svc = { mode?: "http" | "tcp"; pinned?: boolean; lb_port: number; targets: Record<string, string | string[]>; bluegreen?: { service: string; active?: "blue" | "green" }; check?: Check; cache?: "micro" | "honor" | "off" };
type Member = { node: string; ssh: string; weight: number; slice?: Record<string, string> };
type Cluster = {
  domain: string; mesh_port: number; stats_port: number; check_inter_ms: number; check_fall: number; check_rise: number;
  cache_max_size: string; members: Record<string, Member>; services: Record<string, Svc>;
};

const root = join(import.meta.dir, "..");
const deploy = Bun.TOML.parse(await Bun.file(join(root, "deploy.toml")).text()) as any;
const c = deploy.cluster as Cluster;
const ipOf = (m: string) => deploy.nodes[c.members[m].node].public_ip as string;
const names = Object.keys(c.members);
const id = (m: string) => names.indexOf(m) + 1; // stable server ids: identical consistent-hash ring on every member
const shardPort = (s: Svc) => s.lb_port + 10000;
const cached = (s: Svc) => (s.mode ?? "http") === "http" && (s.cache ?? "off") !== "off";
const sni = (svc: string, m: string) => `${svc}.${m}.${c.domain}`;
const TLS = "/etc/aphrody-cluster/tls";
// Origins of a service on a member, primary first. bluegreen: targets[m] is the host, ports come from
// deploy.toml [services.<service>] green_port/blue_port; the active colour is primary, the other one backup.
function addrs(s: Svc, m: string): string[] {
  const t = s.targets[m];
  if (!t) return [];
  if (s.bluegreen) {
    const app = deploy.services[s.bluegreen.service];
    const act = s.bluegreen.active ?? "green";
    const ports = act === "green" ? [app.green_port, app.blue_port] : [app.blue_port, app.green_port];
    return ports.map((p: number) => `${t}:${p}`);
  }
  return Array.isArray(t) ? t : [t];
}
// HAProxy server lines for local origins: first primary, the rest backup, all health-checked.
const originServers = (name: string, base: number, w: number | null, list: string[]) =>
  list.map((a, i) => `    server ${i ? `${name}-b${i}` : name} ${a}${base ? ` id ${base + 100 * i}` : ""}${w ? ` weight ${w}` : ""}${i ? " backup" : ""} check`);

function haproxy(self: string): string {
  const out: string[] = [
    `# GENERATED by infra/cluster/gen.ts from infra/deploy.toml [cluster]; member ${self}. Do not edit.`,
    "global",
    "    log stderr format short local0 notice",
    "    user haproxy",
    "    group haproxy",
    "    maxconn 20000",
    "    stats socket /run/aphrody-cluster/haproxy.sock mode 600 level admin",
    "    ssl-default-bind-options ssl-min-ver TLSv1.3",
    "    ssl-default-server-options ssl-min-ver TLSv1.3",
    "",
    "defaults",
    "    log global",
    "    mode http",
    "    option dontlognull",
    "    timeout connect 3s",
    "    timeout client 120s",
    "    timeout server 120s",
    "    timeout tunnel 1h",
    "    timeout http-keep-alive 10s",
    "    timeout check 2s",
    "    retries 2",
    "    option redispatch 1",
    `    default-server inter ${c.check_inter_ms}ms fastinter 500ms downinter 3s fall ${c.check_fall} rise ${c.check_rise}`,
    "",
    "frontend stats",
    `    bind 127.0.0.1:${c.stats_port}`,
    "    http-request use-service prometheus-exporter if { path /metrics }",
    "    stats enable",
    "    stats uri /stats",
    "    stats refresh 5s",
    "",
    "# Inbound from other members: TLS 1.3, client cert signed by the cluster CA, routed by SNI.",
    "frontend mesh_in",
    "    mode tcp",
    `    bind ${ipOf(self)}:${c.mesh_port} ssl crt ${TLS}/host.pem ca-file ${TLS}/ca.pem verify required`,
    `    tcp-request content reject unless { ssl_fc_sni -m end .${self}.${c.domain} }`,
  ];
  const local = Object.entries(c.services).filter(([, s]) => s.targets[self]);
  for (const [n] of local) out.push(`    use_backend in_${n} if { ssl_fc_sni -i ${sni(n, self)} }`);
  out.push("");
  for (const [n, s] of local) {
    out.push(`backend in_${n}`, "    mode tcp",
      ...(cached(s) ? [`    server local 127.0.0.1:${shardPort(s)}`] : originServers("local", 0, null, addrs(s, self))), "");
  }
  for (const [n, s] of Object.entries(c.services).filter(([, s]) => !s.pinned)) {
    const tcp = s.mode === "tcp";
    out.push(`frontend lb_${n}`, `    bind 127.0.0.1:${s.lb_port}`, `    mode ${tcp ? "tcp" : "http"}`);
    if (!tcp) out.push(`    http-request set-header X-Cluster-Entry ${self}`);
    out.push(`    default_backend pool_${n}`, "", `backend pool_${n}`, `    mode ${tcp ? "tcp" : "http"}`);
    if (tcp) out.push("    balance roundrobin");
    else {
      const ck = s.check!;
      out.push(
        "    balance uri whole",
        "    hash-type consistent",
        "    option httpchk",
        `    http-check send meth GET uri ${ck.path} ver HTTP/1.1 hdr Host ${ck.host} hdr X-Cluster-Check 1`,
        `    http-check expect ${ck.expect}`,
        "    retry-on conn-failure empty-response response-timeout 500 502 503 504",
        "    http-request disable-l7-retry if !METH_GET !METH_HEAD",
      );
    }
    for (const m of names.filter((m) => s.targets[m])) {
      const w = c.members[m].weight;
      if (m === self) {
        if (cached(s)) out.push(`    server ${m} 127.0.0.1:${shardPort(s)} id ${id(m)} weight ${w} check`);
        else out.push(...originServers(m, id(m), w, addrs(s, m)));
      } else {
        const h = sni(n, m);
        out.push(
          `    server ${m} ${ipOf(m)}:${c.mesh_port} id ${id(m)} weight ${w} check ssl crt ${TLS}/host.pem ca-file ${TLS}/ca.pem verify required verifyhost ${h} sni str(${h}) check-sni ${h}`,
        );
      }
    }
    out.push("");
  }
  return out.join("\n");
}

function nginx(self: string): string {
  const shards = Object.entries(c.services).filter(([, s]) => s.targets[self] && cached(s));
  const out: string[] = [
    `# GENERATED by infra/cluster/gen.ts from infra/deploy.toml [cluster]; member ${self}. Do not edit.`,
    "# Cache shards: HAProxy hashes each URI to one member cluster-wide, so proxy_cache_lock on that member",
    "# collapses concurrent duplicates of the whole cluster into one origin fetch.",
    `proxy_cache_path /var/cache/nginx/aphrody-cluster levels=1:2 keys_zone=acl_cache:64m max_size=${c.cache_max_size} inactive=1h use_temp_path=off;`,
    "proxy_cache_path /var/cache/nginx/aphrody-cluster-idem levels=1:2 keys_zone=acl_idem:16m max_size=256m inactive=24h use_temp_path=off;",
    "log_format acl_log '$time_iso8601 $server_port $request_method $host $uri $status $upstream_cache_status $request_time $http_x_cluster_entry';",
    'map "$http_authorization$http_cookie" $acl_private { "" 0; default 1; }',
    'map $http_x_cluster_check $acl_check { "" 0; default 1; }',
    'map $http_x_cluster_check $acl_logit { "" 1; default 0; }',
    'map "$request_method:$http_idempotency_key" $acl_idem { "~^POST:.+" 1; default 0; }',
    "",
  ];
  for (const [n, s] of shards) {
    const micro = s.cache === "micro" ? "        proxy_cache_valid 200 301 302 404 1s;\n" : "";
    out.push(`upstream acl_${n} { ${addrs(s, self).map((a, i) => `server ${a}${i ? " backup" : " max_fails=1 fail_timeout=3s"};`).join(" ")} keepalive 16; }`);
    out.push(`server {
    listen 127.0.0.1:${shardPort(s)};
    access_log /var/log/nginx/aphrody-cluster.log acl_log if=$acl_logit;
    proxy_http_version 1.1;
    proxy_set_header Connection "";
    proxy_set_header Host $host;
    proxy_set_header X-Forwarded-For $http_x_forwarded_for;
    proxy_set_header X-Forwarded-Proto https;
    location / {
        error_page 418 = @idem;
        if ($acl_idem) { return 418; }
        proxy_pass http://acl_${n};
        proxy_next_upstream error timeout http_502 http_503 http_504;
        proxy_cache acl_cache;
        proxy_cache_key "${n}|$host$request_uri";
        proxy_cache_lock on;
        proxy_cache_lock_timeout 15s;
        proxy_cache_lock_age 15s;
        proxy_cache_use_stale error timeout updating http_500 http_502 http_503 http_504;
        proxy_cache_background_update on;
        proxy_cache_revalidate on;
        proxy_cache_bypass $acl_private $acl_check;
        proxy_no_cache $acl_private $acl_check;
${micro}        add_header X-Cluster-Cache $upstream_cache_status always;
        add_header X-Cluster-Shard ${self} always;
    }
    # POST + Idempotency-Key: first response replayed for 24 h, concurrent duplicates coalesced.
    location @idem {
        proxy_pass http://acl_${n};
        proxy_cache acl_idem;
        proxy_cache_methods POST;
        proxy_cache_key "${n}|$request_method|$host$request_uri|$http_idempotency_key|$http_authorization|$http_cookie";
        proxy_cache_lock on;
        proxy_cache_lock_timeout 30s;
        proxy_ignore_headers Cache-Control Expires Set-Cookie Vary;
        proxy_cache_valid 200 201 202 204 400 401 403 404 405 409 422 24h;
        add_header X-Idempotent-Replay $upstream_cache_status always;
        add_header X-Cluster-Shard ${self} always;
    }
}
`);
  }
  if (c.services.bench?.targets[self]) {
    out.push(`server {
    listen 29990; # loopback + WireGuard subnet (comparison only), no bind on the wg interface
    allow 127.0.0.1;
    allow 10.200.77.0/24;
    deny all;
    access_log off;
    root /var/lib/aphrody-cluster;
    location /bench/ { }
}
`);
  }
  return out.join("\n");
}

function slice(self: string): string {
  const s = c.members[self].slice ?? {};
  return ["# GENERATED by infra/cluster/gen.ts. Cluster workloads (HAProxy, edge containers) run here.", "[Slice]",
    ...Object.entries(s).map(([k, v]) => `${k}=${v}`), ""].join("\n");
}

// ssh over the mesh: <member>-mesh aliases on the members (the PC is outside the fleet-IP firewall of 7444).
// ProxyCommand /usr/local/bin/aphrody-ssh-mesh; client cert ~/.config/aphrody-cluster/{client.pem,ca.pem}.
function sshConfig(): string {
  const out = ["# GENERATED by infra/cluster/gen.ts: ssh to <member>-mesh = sshd through the mTLS mesh (TCP " + c.mesh_port + ").", ""];
  for (const m of names) {
    out.push(`Host ${m}-mesh`, `    HostName ${ipOf(m)}`, `    HostKeyAlias ${m}`,
      "    StrictHostKeyChecking accept-new # server already authenticated by the mesh certificate",
      "    ConnectTimeout 10", "    ServerAliveInterval 15", `    ProxyCommand /usr/local/bin/aphrody-ssh-mesh ${m}`, "");
  }
  return out.join("\n");
}

function sshMesh(): string {
  const table = names.map((m) => `  ${m}) ip=${ipOf(m)} ;;`).join("\n");
  return `#!/bin/sh
# GENERATED by infra/cluster/gen.ts. ProxyCommand: sshd of <member> through the mTLS mesh (TCP ${c.mesh_port}).
# Cert: \$APHRODY_CLUSTER_DIR (default ~/.config/aphrody-cluster) holding client.pem (cert+key) and ca.pem.
d=\${APHRODY_CLUSTER_DIR:-\$HOME/.config/aphrody-cluster}
case "\$1" in
${table}
  *) echo "aphrody-ssh-mesh: unknown member \$1" >&2; exit 2 ;;
esac
sni="ssh.\$1.${c.domain}"
exec openssl s_client -quiet -verify_quiet -verify_return_error -verify_hostname "\$sni" -servername "\$sni" \\
  -CAfile "\$d/ca.pem" -cert "\$d/client.pem" -connect "\$ip:${c.mesh_port}"
`;
}

mkdirSync(join(import.meta.dir, "generated", "ssh"), { recursive: true });
writeFileSync(join(import.meta.dir, "generated", "ssh", "ssh_config.host"), sshConfig());
writeFileSync(join(import.meta.dir, "generated", "ssh", "aphrody-ssh-mesh"), sshMesh());

for (const m of names) {
  const dir = join(import.meta.dir, "generated", m);
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "haproxy.cfg"), haproxy(m) + "\n");
  writeFileSync(join(dir, "nginx-cluster.conf"), nginx(m));
  writeFileSync(join(dir, "aphrody-cluster.slice"), slice(m));
}
console.log(`generated ${names.join(", ")}`);
