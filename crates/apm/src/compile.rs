//! `apm compile` (single-file mode): AGENTS.md for Copilot (`compilation/template_builder.py`)
//! and CLAUDE.md for Claude (`compilation/claude_formatter.py`).
//!
//! Upstream defaults to distributed placement (one AGENTS.md per matched
//! directory); this port emits a single root file per target family.

use std::fs;
use std::path::Path;
use std::path::PathBuf;

use anyhow::Result;

use crate::deploy;
use crate::frontmatter;
use crate::hash;
use crate::install::APM_VERSION;
use crate::install::LOCKFILE_NAME;
use crate::install::{self};
use crate::lockfile::LockFile;
use crate::manifest::Manifest;
use crate::targets::Target;
use crate::targets::{self};

pub const BUILD_ID_PLACEHOLDER: &str = "<!-- Build ID: __BUILD_ID__ -->";
pub const AGENTS_MD_GENERATED_MARKER: &str = "<!-- Generated by APM CLI from .apm/ primitives -->";
pub const CLAUDE_HEADER: &str = "<!-- Generated by APM CLI -->";

#[derive(Debug, Clone)]
pub struct Instruction {
    pub file_path: PathBuf,
    pub apply_to: String,
    pub content: String,
}

/// `stabilize_build_id`.
pub fn stabilize_build_id(content: &str) -> String {
    let lines: Vec<&str> = content.lines().collect();
    let Some(idx) = lines.iter().position(|l| *l == BUILD_ID_PLACEHOLDER) else {
        return content.to_owned();
    };
    let input: Vec<&str> = lines
        .iter()
        .enumerate()
        .filter(|(i, _)| *i != idx)
        .map(|(_, l)| *l)
        .collect();
    let id = &hash::sha256_hex(input.join("\n").as_bytes())[..12];
    content.replacen(BUILD_ID_PLACEHOLDER, &format!("<!-- Build ID: {id} -->"), 1)
}

fn rel(base: &Path, p: &Path) -> String {
    p.strip_prefix(base)
        .unwrap_or(p)
        .to_string_lossy()
        .replace('\\', "/")
}

/// `render_instructions_block`: globals first, then groups sorted by pattern.
fn render_block(
    instructions: &[Instruction],
    base: &Path,
    prefix: &str,
    emit: &dyn Fn(&Instruction) -> Vec<String>,
) -> Vec<String> {
    let mut out = Vec::new();
    let mut globals: Vec<&Instruction> = instructions
        .iter()
        .filter(|i| i.apply_to.is_empty())
        .collect();
    globals.sort_by_key(|i| rel(base, &i.file_path));
    if !globals.is_empty() {
        out.push(format!("{prefix} Global Instructions"));
        out.push(String::new());
        for i in globals {
            if !i.content.trim().is_empty() {
                out.extend(emit(i));
            }
        }
    }
    let mut patterns: Vec<&str> = instructions
        .iter()
        .filter(|i| !i.apply_to.is_empty())
        .map(|i| i.apply_to.as_str())
        .collect();
    patterns.sort_unstable();
    patterns.dedup();
    for pat in patterns {
        out.push(format!("{prefix} Files matching `{pat}`"));
        out.push(String::new());
        let mut group: Vec<&Instruction> =
            instructions.iter().filter(|i| i.apply_to == pat).collect();
        group.sort_by_key(|i| rel(base, &i.file_path));
        for i in group {
            if !i.content.trim().is_empty() {
                out.extend(emit(i));
            }
        }
    }
    out
}

pub fn agents_md(instructions: &[Instruction], base: &Path) -> String {
    let emit = |i: &Instruction| {
        let r = rel(base, &i.file_path);
        vec![
            format!("<!-- Source: {r} -->"),
            i.content.trim().to_owned(),
            format!("<!-- End source: {r} -->"),
            String::new(),
        ]
    };
    let mut s = vec![
        "# AGENTS.md".to_owned(),
        AGENTS_MD_GENERATED_MARKER.into(),
        BUILD_ID_PLACEHOLDER.into(),
        format!("<!-- APM Version: {APM_VERSION} -->"),
        String::new(),
    ];
    if !instructions.is_empty() {
        s.push(render_block(instructions, base, "##", &emit).join("\n"));
    }
    s.extend([
        "---".into(),
        "*This file was generated by APM CLI. Do not edit manually.*".into(),
        "*To regenerate: `apm compile`*".into(),
        String::new(),
    ]);
    stabilize_build_id(&s.join("\n"))
}

pub fn claude_md(instructions: &[Instruction], base: &Path, skip_instructions: bool) -> String {
    let emit = |i: &Instruction| vec![i.content.trim().to_owned(), String::new()];
    let mut s = vec![
        "# CLAUDE.md".to_owned(),
        CLAUDE_HEADER.into(),
        BUILD_ID_PLACEHOLDER.into(),
        String::new(),
    ];
    if !instructions.is_empty() && !skip_instructions {
        s.push("## Project Standards".into());
        s.push(String::new());
        s.extend(render_block(instructions, base, "###", &emit));
    }
    stabilize_build_id(&s.join("\n"))
}

fn load_instructions(dirs: &[(PathBuf, bool)]) -> Result<Vec<Instruction>> {
    let mut out = Vec::new();
    for (dir, include_root) in dirs {
        for f in deploy::find_instructions(dir, *include_root) {
            let post = frontmatter::loads(&fs::read_to_string(&f)?)?;
            out.push(Instruction {
                file_path: f,
                apply_to: deploy::apply_to_of(&post.metadata),
                content: post.content,
            });
        }
    }
    Ok(out)
}

/// Compile for the given (or detected) targets; returns written file paths.
pub fn compile(project_root: &Path, cli_targets: &[String]) -> Result<Vec<PathBuf>> {
    let manifest = Manifest::load(&project_root.join("apm.yml"))?;
    let mut explicit = Vec::new();
    for t in cli_targets
        .iter()
        .flat_map(|s| s.split(','))
        .map(str::trim)
        .filter(|s| !s.is_empty())
    {
        explicit.push(crate::manifest::normalize_target(t)?);
    }
    if explicit.is_empty() {
        explicit.clone_from(&manifest.targets);
    }
    let (ts, _) = targets::active_targets(project_root, &explicit);
    let mut dirs = vec![(project_root.to_path_buf(), false)];
    if let Some(lock) = LockFile::read(&project_root.join(LOCKFILE_NAME))? {
        dirs.extend(
            install::installed_package_dirs(project_root, &lock)
                .into_iter()
                .map(|d| (d, true)),
        );
    }
    let instructions = load_instructions(&dirs)?;
    let mut written = Vec::new();
    let mut families: Vec<&str> = Vec::new();
    for t in ts.iter().filter_map(|t: &Target| t.compile_output) {
        if families.contains(&t) {
            continue;
        }
        families.push(t);
        let path = project_root.join(t);
        let text = if t == "CLAUDE.md" {
            claude_md(
                &instructions,
                project_root,
                project_root.join(".claude").join("rules").is_dir(),
            )
        } else {
            agents_md(&instructions, project_root)
        };
        fs::write(&path, text)?;
        written.push(path);
    }
    Ok(written)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn build_id_is_deterministic_and_replaced() {
        let a = stabilize_build_id(&format!("# X\n{BUILD_ID_PLACEHOLDER}\nbody\n"));
        assert!(!a.contains("__BUILD_ID__"));
        assert_eq!(
            a,
            stabilize_build_id(&format!("# X\n{BUILD_ID_PLACEHOLDER}\nbody\n"))
        );
        let expected = &hash::sha256_hex(b"# X\nbody")[..12];
        assert!(a.contains(&format!("<!-- Build ID: {expected} -->")));
    }

    #[test]
    fn agents_md_groups_global_then_patterns() {
        let base = Path::new("/p");
        let ins = vec![
            Instruction {
                file_path: base.join(".apm/instructions/py.instructions.md"),
                apply_to: "**/*.py".into(),
                content: "Use ruff.\n".into(),
            },
            Instruction {
                file_path: base.join(".apm/instructions/all.instructions.md"),
                apply_to: String::new(),
                content: "Be kind.\n".into(),
            },
        ];
        let out = agents_md(&ins, base);
        let g = out.find("## Global Instructions").unwrap();
        let p = out.find("## Files matching `**/*.py`").unwrap();
        assert!(g < p);
        assert!(out.contains("<!-- Source: .apm/instructions/all.instructions.md -->\nBe kind.\n<!-- End source: .apm/instructions/all.instructions.md -->"));
        assert!(out.ends_with("*To regenerate: `apm compile`*\n"));
    }
}
