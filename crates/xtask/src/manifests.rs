//! pin-001: `src.lock.json` is the only pin of external repositories. Everything else is derived
//! from it by `ay manifests` and verified by `ay manifests --check` (CI gate, `just check`):
//!
//! - `DEPS` (gclient): every locked repository with a remote and a commit;
//! - `.gitmodules`: the gitlinks of the superproject index, with URL and branch from the lock;
//!   `--check` also fails when a gitlink commit differs from the locked commit;
//! - `docs/patches/series` and `packages/bun-parity/patches/series` (quilt indexes of patches tracked in
//!   this tree; `third_party/` is not versioned, so nothing under it is indexed).
//!
//! `MAINTAINERS` is hand-maintained (kernel format) and never generated. The org URL in the DEPS
//! vars comes from `identity.toml` (`[orgs].main`), read without a TOML dependency.

use crate::{LockedRepo, SrcLock};
use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

/// `[orgs].main` from identity.toml (single identity source); empty when absent.
pub fn main_org(root: &Path) -> String {
    fs::read_to_string(root.join("identity.toml")).map(|t| toml_value(&t, "orgs", "main")).unwrap_or_default()
}

/// `key = "value"` of `[table]` in a flat TOML file (identity.toml has no nesting xtask needs).
pub fn toml_value(text: &str, table: &str, key: &str) -> String {
    let mut inside = false;
    for line in text.lines().map(str::trim) {
        if line.starts_with('[') {
            inside = line == format!("[{table}]");
        } else if inside {
            if let Some((k, v)) = line.split_once('=') {
                if k.trim() == key {
                    let v = v.trim();
                    return v.strip_prefix('"').and_then(|v| v.split_once('"')).map_or("", |(v, _)| v).to_string();
                }
            }
        }
    }
    String::new()
}

fn pinned(repo: &LockedRepo) -> bool {
    !repo.url.starts_with("local:") && !repo.commit.starts_with("0000000") && repo.commit.len() == 40
}

pub fn render_deps(locked: &BTreeMap<String, LockedRepo>, org: &str) -> String {
    let rev = |p: &str| locked.get(p).map_or("HEAD", |r| r.commit.as_str());
    let mut out = String::new();
    out.push_str("# gclient DEPS, generated by `ay manifests` from src.lock.json (pin-001). Do not edit.\n\n");
    out.push_str("use_relative_paths = True\ngit_dependencies = 'SYNC'\n\nvars = {\n");
    if !org.is_empty() {
        out.push_str(&format!("  'org_github': 'https://github.com/{org}',\n"));
    }
    out.push_str("  'chromium_git': 'https://chromium.googlesource.com',\n");
    out.push_str(&format!("  'chromium_revision': '{}',\n", rev("third_party/chromium/src")));
    out.push_str(&format!("  'depot_tools_revision': '{}',\n", rev("third_party/depot_tools")));
    out.push_str(&format!("  'linux_kernel_revision': '{}',\n", rev("third_party/linux")));
    out.push_str("}\n\ndeps = {\n");
    for (path, repo) in locked.iter().filter(|(_, r)| pinned(r)) {
        out.push_str(&format!("  '{path}': '{}@{}',\n", repo.url, repo.commit));
    }
    out.push_str("}\n\nrecursedeps = [\n  'third_party/chromium/src',\n]\n\n");
    out.push_str("hooks = [\n  {\n    'name': 'ay_git_audit',\n    'pattern': '.',\n    'action': ['ay', 'git', 'audit'],\n  },\n]\n");
    out
}

/// `git ls-files -s` of the superproject; an error (no git, safe.directory, ...) is reported, never
/// read as "no submodules".
pub fn ls_files_stage(root: &Path) -> Result<String, String> {
    let o = Command::new("git")
        .args(["-C", &root.to_string_lossy(), "ls-files", "-s"])
        .output()
        .map_err(|e| format!("git ls-files: {e}"))?;
    if !o.status.success() {
        return Err(format!("git ls-files: {}", String::from_utf8_lossy(&o.stderr).trim()));
    }
    Ok(String::from_utf8_lossy(&o.stdout).into_owned())
}

pub fn parse_gitlinks(ls_files_s: &str) -> BTreeMap<String, String> {
    ls_files_s
        .lines()
        .filter_map(|l| {
            let (meta, path) = l.split_once('\t')?;
            let mut f = meta.split_whitespace();
            (f.next()? == "160000").then(|| (path.to_string(), f.next().unwrap_or("").to_string()))
        })
        .collect()
}

pub fn render_gitmodules(locked: &BTreeMap<String, LockedRepo>, links: &BTreeMap<String, String>) -> String {
    let mut out = String::from("# Generated by `ay manifests` from src.lock.json (pin-001). Do not edit.\n");
    for path in links.keys() {
        let Some(repo) = locked.get(path) else { continue };
        out.push_str(&format!("[submodule \"{path}\"]\n\tpath = {path}\n\turl = {}\n", repo.url));
        if repo.branch != "detached" && !repo.branch.is_empty() {
            out.push_str(&format!("\tbranch = {}\n", repo.branch));
        }
    }
    out
}

fn patch_names(dir: &Path) -> Vec<String> {
    let mut names: Vec<String> = fs::read_dir(dir)
        .into_iter()
        .flatten()
        .flatten()
        .filter_map(|e| e.file_name().into_string().ok())
        .filter(|n| n.ends_with(".patch"))
        .collect();
    names.sort();
    names
}

/// Every derived file with its expected content.
pub fn render_all(root: &Path, lock: &SrcLock, links: &BTreeMap<String, String>) -> Vec<(PathBuf, String)> {
    let mut files = vec![
        (root.join("DEPS"), render_deps(&lock.repositories, &main_org(root))),
        (root.join(".gitmodules"), render_gitmodules(&lock.repositories, links)),
    ];
    let bun_patches = root.join("packages").join("bun-parity").join("patches");
    let mut series = vec![
        "# quilt series (generated by `ay manifests`): <patch relative to docs/patches> -p1".to_string(),
    ];
    let bun = patch_names(&bun_patches);
    series.extend(bun.iter().map(|n| format!("../../packages/bun-parity/patches/{n} -p1")));
    files.push((root.join("docs").join("patches").join("series"), format!("{}\n", series.join("\n"))));
    if bun_patches.is_dir() {
        files.push((bun_patches.join("series"), format!("{}\n", bun.join("\n"))));
    }
    files
}

pub fn load_lock(root: &Path) -> Result<SrcLock, String> {
    let p = root.join("src.lock.json");
    let text = fs::read_to_string(&p).map_err(|e| format!("{}: {e}", p.display()))?;
    serde_json::from_str(&text).map_err(|e| format!("{}: {e}", p.display()))
}

/// Write the derived files (or, with `check`, report drift and gitlink/lock mismatches). Exit code.
pub fn run(root: &Path, check: bool) -> i32 {
    let lock = match load_lock(root) {
        Ok(l) => l,
        Err(e) => {
            eprintln!("manifests: {e}");
            return 1;
        }
    };
    let listing = match ls_files_stage(root) {
        Ok(l) => l,
        Err(e) => {
            eprintln!("manifests: {e}");
            return 1;
        }
    };
    let links = parse_gitlinks(&listing);
    let files = render_all(root, &lock, &links);
    if !check {
        for (path, text) in &files {
            if let Some(dir) = path.parent() {
                let _ = fs::create_dir_all(dir);
            }
            if let Err(e) = fs::write(path, text) {
                eprintln!("manifests: {}: {e}", path.display());
                return 1;
            }
            println!("wrote {}", path.display());
        }
        return 0;
    }
    let mut drift = 0;
    for (path, text) in &files {
        let have = fs::read_to_string(path).unwrap_or_default().replace("\r\n", "\n");
        if &have != text {
            eprintln!("manifests: {} is stale (run `ay manifests`)", path.display());
            drift += 1;
        }
    }
    for (path, commit) in &links {
        match lock.repositories.get(path.as_str()) {
            Some(r) if &r.commit == commit => {}
            Some(r) => {
                eprintln!("manifests: gitlink {path} at {commit}, src.lock.json pins {} (run `ay lock`)", r.commit);
                drift += 1;
            }
            None => {
                eprintln!("manifests: gitlink {path} missing from src.lock.json (run `ay lock`)");
                drift += 1;
            }
        }
    }
    // Reverse drift: a locked first-party path must exist in the index, as a gitlink or as tracked files.
    for path in lock.repositories.keys().filter(|p| !p.starts_with("third_party/")) {
        let tracked = links.contains_key(path)
            || listing.lines().any(|l| l.split_once('\t').is_some_and(|(_, f)| f.starts_with(&format!("{path}/"))));
        if !tracked {
            eprintln!("manifests: {path} is locked in src.lock.json but neither a gitlink nor tracked (run `ay lock`)");
            drift += 1;
        }
    }
    if drift == 0 {
        println!("manifests: DEPS, .gitmodules and patch series match src.lock.json");
    }
    i32::from(drift > 0)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn repo(url: &str, commit: &str, branch: &str) -> LockedRepo {
        LockedRepo {
            path: String::new(),
            url: url.into(),
            upstream_url: None,
            commit: commit.into(),
            branch: branch.into(),
            engine: "git".into(),
            pillar: "monorepo".into(),
            remotes: None,
            sparse_paths: None,
        }
    }

    #[test]
    fn identity_org() {
        let t = "[product]\nmain = \"x\"\n[orgs]\nmain = \"org-a\"     # comment\nlab = \"b\"\n";
        assert_eq!(toml_value(t, "orgs", "main"), "org-a");
        assert_eq!(toml_value(t, "orgs", "none"), "");
    }

    #[test]
    fn deps_and_gitmodules_come_from_the_lock() {
        let c = "4c7244a405d326e284710231ff609168dceb9044";
        let mut lock = BTreeMap::new();
        lock.insert("apps/x".to_string(), repo("https://github.com/o/x.git", c, "main"));
        lock.insert("third_party/l".to_string(), repo("local:third_party/l", c, "main"));
        let deps = render_deps(&lock, "o");
        assert!(deps.contains(&format!("'apps/x': 'https://github.com/o/x.git@{c}'")));
        assert!(deps.contains("'org_github': 'https://github.com/o'"));
        assert!(!deps.contains("third_party/l"));
        let links = parse_gitlinks(&format!("100644 abc 0\tREADME.md\n160000 {c} 0\tapps/x\n"));
        assert_eq!(links.get("apps/x").map(String::as_str), Some(c));
        let gm = render_gitmodules(&lock, &links);
        assert!(gm.contains("[submodule \"apps/x\"]\n\tpath = apps/x\n\turl = https://github.com/o/x.git\n\tbranch = main\n"));
    }
}
