//! Zero-dependency pure-Rust CPU font atlas builder (`1024x128` RGBA8) for printable ASCII.
//! Shared identically between native Desktop (`winit` + `wgpu`) and `wasm32` WebGPU targets.

/// Atlas dimensions in pixels (`16 cols * 64px`? Wait: `16 cols * 16px`? Let's use `512x128` with 32x16 cells).
/// 96 characters (ASCII 32..=127) fit cleanly in 16 columns x 6 rows of `16x16` cells -> `256x96` RGBA!
/// Wait: using `16x16` cells inside a `256x128` texture gives `1px` empty gutter around an `8x12` or `8x8` glyph,
/// eliminating linear-filter bleeding between neighboring characters!
pub const ATLAS_W: u32 = 256;
pub const ATLAS_H: u32 = 128;
pub const CELL_W: u32 = 16;
pub const CELL_H: u32 = 16;
pub const COLS: u32 = 16;

/// Returns `(u0, v0, uw, vh)` normalized atlas coordinates for ASCII character `ch`.
#[must_use]
pub fn glyph_uv(ch: char) -> [f32; 4] {
    let code = if ch.is_ascii() && (ch as u32) >= 32 && (ch as u32) < 127 {
        (ch as u32) - 32
    } else {
        ('?' as u32) - 32
    };
    let col = code % COLS;
    let row = code / COLS;
    // Inset slightly inside the 16x16 cell where the 8x8 glyph sits at (4..12, 4..12)
    let x0 = (col * CELL_W + 3) as f32 / ATLAS_W as f32;
    let y0 = (row * CELL_H + 3) as f32 / ATLAS_H as f32;
    let w = 10.0 / ATLAS_W as f32;
    let h = 10.0 / ATLAS_H as f32;
    [x0, y0, w, h]
}

/// Builds the RGBA8 font atlas (`ATLAS_W * ATLAS_H * 4` bytes).
#[must_use]
pub fn build_rgba_atlas() -> Vec<u8> {
    let mut pixels = vec![0u8; (ATLAS_W * ATLAS_H * 4) as usize];
    for idx in 0..95u32 {
        let ch = char::from_u32(idx + 32).unwrap_or('?');
        let rows = glyph_bitmap(ch);
        let col = idx % COLS;
        let row = idx / COLS;
        let base_x = col * CELL_W + 4;
        let base_y = row * CELL_H + 4;
        for (ry, bits) in rows.iter().enumerate() {
            for rx in 0..8u32 {
                if (bits >> (7 - rx)) & 1 == 1 {
                    let px = base_x + rx;
                    let py = base_y + ry as u32;
                    let off = ((py * ATLAS_W + px) * 4) as usize;
                    pixels[off] = 255;
                    pixels[off + 1] = 255;
                    pixels[off + 2] = 255;
                    pixels[off + 3] = 255;
                }
            }
        }
    }
    pixels
}

